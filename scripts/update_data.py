#!/usr/bin/env python3
"""Refresh the site data from Google Scholar and GitHub.

Writes (all generated, do not edit by hand):
  _data/publications.yml  publications from Scholar, linked to their repos
  _data/scholar.yml       citation metrics
  _data/repos.yml         GitHub projects (own repos + org repos I contributed to)
  _data/sync.yml          date of the last data change
and prepends an entry to _data/news.yml when a new publication shows up.

Manual curation lives in _data/curation.yml and is applied on every run.
If Scholar or GitHub cannot be reached, the existing data is kept.

Usage:
  python scripts/update_data.py
  python scripts/update_data.py --no-scholar --no-github   # only re-apply curation
"""

import argparse
import datetime as dt
import difflib
import html
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "_data"

SCHOLAR_ID = "et4jCA4AAAAJ"
GITHUB_USER = "giuseppericcio"
GITHUB_ORGS = ["PRAISELab-PicusLab"]

GITHUB_TOKEN = os.environ.get("GITHUB_TOKEN")
USER_AGENT = f"{GITHUB_USER}.github.io data updater (+https://github.com/{GITHUB_USER}/{GITHUB_USER}.github.io)"

NEWS_HEADER = ("News (newest first). Markdown allowed. Edit freely: scripts/update_data.py\n"
               "only prepends an entry (auto: true) when a new paper appears on Scholar.")
GENERATED = "# Generated by scripts/update_data.py - edit _data/curation.yml instead.\n"


# --------------------------------------------------------------------------- io

def load_yaml(name, default):
    path = DATA / name
    if not path.exists():
        return default
    with path.open(encoding="utf-8") as f:
        return yaml.safe_load(f) or default


def dump_yaml(name, data, header, generated=True):
    path = DATA / name
    text = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000)
    new = "".join(f"# {line}\n" for line in header.splitlines()) + (GENERATED if generated else "") + text
    if path.exists() and path.read_text(encoding="utf-8") == new:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def http_get(url, headers=None):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, **(headers or {})})
    with urllib.request.urlopen(req, timeout=30) as r:
        # Scholar may answer in Latin-1 depending on the client locale
        return r.read().decode(r.headers.get_content_charset() or "utf-8", errors="replace")


# ---------------------------------------------------------------------- helpers

def norm(text):
    text = html.unescape(text or "").lower()
    return re.sub(r"[^a-z0-9]+", " ", text).strip()


def slugify(text, maxlen=60):
    return norm(text).replace(" ", "-")[:maxlen].strip("-")


# ---------------------------------------------------------------------- scholar

def fetch_scholar():
    url = (f"https://scholar.google.com/citations?user={SCHOLAR_ID}"
           "&hl=en&cstart=0&pagesize=100&sortby=pubdate")
    page = http_get(url)
    if "gsc_a_tr" not in page:
        raise RuntimeError("profile page did not contain publications (blocked?)")

    def strip(s):
        return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()

    articles = []
    for row in re.findall(r'<tr class="gsc_a_tr">(.*?)</tr>', page, re.S):
        title = re.search(r'class="gsc_a_at"[^>]*>(.*?)</a>', row, re.S)
        href = re.search(r'href="(/citations\?view_op=view_citation[^"]+)"', row)
        grays = re.findall(r'<div class="gs_gray">(.*?)</div>', row, re.S)
        cites = re.search(r'class="gsc_a_ac[^"]*"[^>]*>(\d*)</a>', row)
        year = re.search(r'class="gsc_a_h gsc_a_hc gs_ibl">(\d{4})<', row)
        venue = strip(re.sub(r'<span class="gs_oph">.*?</span>', "", grays[1])) if len(grays) > 1 else ""
        if not title:
            continue
        articles.append({
            "title": strip(title.group(1)),
            "authors": [a.strip() for a in strip(grays[0]).split(",") if a.strip()] if grays else [],
            "venue": re.sub(r",\s*\d{4}$", "", venue),
            "year": int(year.group(1)) if year else None,
            "citations": int(cites.group(1)) if cites and cites.group(1) else 0,
            "scholar_url": "https://scholar.google.com" + html.unescape(href.group(1)) if href else None,
        })

    nums = [int(x) for x in re.findall(r'<td class="gsc_rsb_std">(\d+)</td>', page)]
    stats = {"citations": nums[0], "h_index": nums[2], "i10_index": nums[4]} if len(nums) >= 6 else {}
    print(f"Scholar: {len(articles)} publications")
    return articles, stats


# ----------------------------------------------------------------------- github

def gh_paged(path):
    headers = {"Accept": "application/vnd.github+json"}
    if GITHUB_TOKEN:
        headers["Authorization"] = f"Bearer {GITHUB_TOKEN}"
    out, page = [], 1
    while True:
        sep = "&" if "?" in path else "?"
        chunk = json.loads(http_get(f"https://api.github.com{path}{sep}per_page=100&page={page}", headers))
        out += chunk
        if len(chunk) < 100:
            return out
        page += 1


def repo_entry(r, source):
    return {
        "name": r["name"],
        "full_name": r["full_name"],
        "url": r["html_url"],
        "description": (r.get("description") or "").strip(),
        "homepage": r.get("homepage") or None,
        "language": r.get("language"),
        "stars": r.get("stargazers_count", 0),
        "topics": r.get("topics", [])[:6],
        "pushed_at": (r.get("pushed_at") or "")[:10],
        "source": source,
    }


def fetch_repos(curation):
    featured = curation.get("featured", [])
    repos = []
    for r in gh_paged(f"/users/{GITHUB_USER}/repos?type=owner&sort=pushed"):
        if r["fork"] or r["archived"] or r["name"].lower() in {GITHUB_USER, f"{GITHUB_USER}.github.io"}:
            continue
        repos.append(repo_entry(r, "personal"))

    for org in GITHUB_ORGS:
        for r in gh_paged(f"/orgs/{org}/repos?type=public&sort=pushed"):
            if r["full_name"] not in featured:
                if r["fork"] or r["name"].startswith(".") or r["size"] == 0:
                    continue
                try:
                    logins = {c.get("login", "").lower() for c in gh_paged(f"/repos/{r['full_name']}/contributors")}
                except Exception:
                    logins = set()
                if GITHUB_USER.lower() not in logins:
                    continue
            repos.append(repo_entry(r, org))

    print(f"GitHub: {len(repos)} repositories")
    return repos


def curate_repos(repos, curation):
    hidden, featured = set(curation.get("hidden", [])), curation.get("featured", [])
    out = []
    for r in repos:
        if r["full_name"] in hidden:
            continue
        r.pop("featured", None)
        if r["full_name"] in featured:
            r["featured"] = featured.index(r["full_name"]) + 1
        out.append(r)
    return sorted(out, key=lambda r: r["pushed_at"], reverse=True)


def match_repo(title, repos):
    """Repo whose name or description corresponds to a paper title."""
    t, first = norm(title), norm(title.split(":")[0])
    best, score = None, 0.0
    for r in repos:
        desc = norm(r["description"])
        s = difflib.SequenceMatcher(None, desc, t).ratio()
        if t and t in desc:
            s = 1.0
        if ":" in title and (norm(r["name"]) == first or (len(first) >= 8 and desc.startswith(first + " "))):
            s = 1.0  # "PIE-Med: ..." -> repo PIE-Med, or description repeating the paper name
        if s > score:
            best, score = r, s
    return best if score >= 0.8 else None


# ------------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-scholar", action="store_true")
    ap.add_argument("--no-github", action="store_true")
    args = ap.parse_args()

    curation = load_yaml("curation.yml", {})
    pub_cur = curation.get("publications") or {}
    proj_cur = curation.get("projects") or {}

    old_pubs = load_yaml("publications.yml", [])
    old_titles = {norm(p["title"]) for p in old_pubs}

    articles, stats = None, None
    if not args.no_scholar:
        try:
            articles, stats = fetch_scholar()
        except Exception as e:
            print(f"Scholar failed, keeping existing publications: {e}", file=sys.stderr)
    if not articles:
        articles = old_pubs

    repos = None
    if not args.no_github:
        try:
            repos = fetch_repos(proj_cur)
        except Exception as e:
            print(f"GitHub failed, keeping existing repos: {e}", file=sys.stderr)
    repos = curate_repos(repos if repos is not None else load_yaml("repos.yml", []), proj_cur)

    pubs = []
    for a in articles:
        p = {k: a.get(k) for k in ("title", "authors", "venue", "year", "citations", "scholar_url")}
        p["id"] = slugify(a["title"])
        repo = match_repo(p["title"], repos)
        if repo:
            p["code"] = repo["url"]
            if repo.get("homepage") and "huggingface.co" in repo["homepage"]:
                p["demo" if "/spaces/" in repo["homepage"] else "dataset"] = repo["homepage"]
        cur = pub_cur.get(p["id"]) or {}
        if cur.get("hidden"):
            continue
        p.update(cur)
        pubs.append({k: v for k, v in p.items() if v not in (None, "")})
    pubs.sort(key=lambda p: (-(p.get("year") or 0), -(p.get("citations") or 0)))

    changed = dump_yaml("publications.yml", pubs, "Publications (source: Google Scholar)")
    changed |= dump_yaml("repos.yml", repos, "GitHub repositories")
    if stats:
        stats["profile"] = f"https://scholar.google.com/citations?user={SCHOLAR_ID}"
        changed |= dump_yaml("scholar.yml", stats, "Google Scholar metrics")

    new = [a for a in articles if norm(a["title"]) not in old_titles]
    if old_pubs and new:
        news = load_yaml("news.yml", [])
        month = dt.date.today().strftime("%Y-%m")
        for a in new:
            venue = f" — {a['venue']}" if a.get("venue") else ""
            news.insert(0, {"date": month, "text": f"New paper: *{a['title']}*{venue}", "auto": True})
        changed |= dump_yaml("news.yml", news, NEWS_HEADER, generated=False)
        print(f"News: added {len(new)} entries")

    if changed:
        dump_yaml("sync.yml", {"updated": dt.date.today().isoformat()}, "Date of the last data change")
    print("Data changed" if changed else "No changes")


if __name__ == "__main__":
    main()
